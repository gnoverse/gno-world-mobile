// Usage: node scripts/world-land.mjs
// Writes src/screens/home/full/world-land.ts: the land of the world as one SVG path, for Home's Here Now map.
// Source: world-atlas 2.0.2 land-110m (Natural Earth, public domain). x = longitude, y = −latitude, so the map's
// viewBox is "-180 -84 360 144"; rings wholly south of −60° (Antarctica) are dropped.
import { writeFileSync } from 'node:fs';

const SRC = 'https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-110m.json';
const OUT = new URL('../src/screens/home/full/world-land.ts', import.meta.url);

const topo = await (await fetch(SRC)).json();
const { scale: [sx, sy], translate: [tx, ty] } = topo.transform;

// quantized, delta-encoded arcs → [lon, lat]
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => [(x += dx) * sx + tx, (y += dy) * sy + ty]);
});
// a negative index ~i is arc i reversed; each arc after the first repeats the previous one's last point
const ring = (ids) =>
  ids.flatMap((id, k) => {
    const a = id < 0 ? [...arcs[~id]].reverse() : arcs[id];
    return k ? a.slice(1) : a;
  });

const polygons = topo.objects.land.geometries.flatMap((g) => (g.type === 'Polygon' ? [g.arcs] : g.type === 'MultiPolygon' ? g.arcs : []));
// a ring crossing the 180° meridian (Fiji, Chukotka) jumps from +180 to −180: unwrap it so it stays in one piece,
// then draw it again shifted by 360° so the part past the edge shows on the other side (the viewBox clips the rest)
const unwrap = (pts) => {
  let shift = 0;
  return pts.map(([lon, lat], i) => {
    if (i) {
      const prev = pts[i - 1][0];
      if (lon - prev > 180) shift -= 360;
      else if (prev - lon > 180) shift += 360;
    }
    return [lon + shift, lat];
  });
};

let d = '';
const draw = (pts, dx) => {
  let last = '';
  pts.forEach(([lon, lat], i) => {
    const p = `${+(lon + dx).toFixed(1)} ${+(-lat).toFixed(1)}`;
    if (p === last) return;
    d += (i ? 'L' : 'M') + p;
    last = p;
  });
  d += 'Z';
};
for (const poly of polygons)
  for (const ids of poly) {
    const pts = unwrap(ring(ids));
    if (pts.every(([, lat]) => lat < -60)) continue;
    draw(pts, 0);
    if (pts.some(([lon]) => lon > 180)) draw(pts, -360);
    if (pts.some(([lon]) => lon < -180)) draw(pts, 360);
  }

writeFileSync(
  OUT,
  `// Generated by scripts/world-land.mjs from world-atlas 2.0.2 land-110m (Natural Earth, public domain). Do not edit.\n` +
    `// x = longitude, y = −latitude; viewBox "-180 -84 360 144".\n` +
    `export const LAND_PATH =\n  '${d}';\n`,
);
console.log(`wrote ${OUT.pathname}: ${d.length} characters`);
